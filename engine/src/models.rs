use serde::{Deserialize, Serialize};
use std::collections::HashMap;

/// A customer record in the simulation
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct UserRecord {
    pub tier: String,
    pub user_id: String,
    pub city: String,
    pub gender: String,
    pub acquisition_channel: String,
    pub registered_date: String,
    pub last_active_date: String,
}

/// A discrete funnel event (landing_page, product_view, add_to_cart, checkout, paid)
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FunnelEventRecord {
    pub session_id: String,
    pub tier: String,
    pub user_id: String,
    pub activity: String,
    pub activity_datetime: String,
}

/// A transaction header record (completed purchase)
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TransactionRecord {
    pub session_id: String,
    pub user_id: String,
    pub trx_id: String,
    pub date: String,
    pub tier: String,
    pub total_price: f64,
}

/// A transaction line item (individual product bought in a basket)
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TransactionItemRecord {
    pub trx_id: String,
    pub user_id: String,
    pub tier: String,
    pub date: String,
    pub product: String,
    pub quantity: u32,
    pub unit_price: f64,
    pub total_price: f64,
}

/// Catalog entry exported for download
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CatalogItemRecord {
    pub category: String,
    pub subcategory: String,
    pub product: String,
    pub base_price: f64,
}

/// Daily breakdown metric for charting and trends
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct DailyMetric {
    pub date: String,
    pub weekday: String,
    pub active_visitors: usize,
    pub transactions: usize,
    pub gross_revenue: f64,
    pub items_sold: u32,
    pub conversion_rate: f64,
    pub new_users_acquired: usize,
}

/// High-level summary of the simulation for the web dashboard
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct SimulationSummary {
    pub total_users: usize,
    pub new_users: usize,
    pub total_sessions: usize,
    pub total_transactions: usize,
    pub total_items_sold: u64,
    pub total_revenue: f64,
    pub average_order_value: f64,
    pub overall_conversion_rate: f64,
    pub daily_metrics: Vec<DailyMetric>,
    pub funnel_breakdown: HashMap<String, usize>,
    pub category_revenue: HashMap<String, f64>,
    pub top_products: Vec<(String, u64, f64)>, // (product_name, units_sold, revenue)
}

/// The complete output generated by a simulation run
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SimulationOutput {
    pub users: Vec<UserRecord>,
    pub funnel: Vec<FunnelEventRecord>,
    pub transactions: Vec<TransactionRecord>,
    pub transaction_items: Vec<TransactionItemRecord>,
    pub catalog: Vec<CatalogItemRecord>,
    pub summary: SimulationSummary,
}
